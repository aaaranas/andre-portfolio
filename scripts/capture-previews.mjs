/**
 * Capture a screenshot of every deployed project into public/previews/<id>.jpg
 * and regenerate src/lib/previews.ts, the manifest the project cards read, so
 * they serve their own images instead of hotlinking a third-party screenshot
 * service at render time.
 *
 *   npm run previews            capture every project with a live URL
 *   npm run previews -- pitik   capture just the ones whose id matches
 *
 * Needs a Chromium: `npx playwright install chromium` once, or point
 * PLAYWRIGHT_CHROMIUM_PATH at an existing binary.
 *
 * Run it from a machine that can reach the deployed sites. Re-run it whenever
 * a project's UI changes; the committed PNGs are what visitors actually see.
 */
import { chromium } from "playwright";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "previews");

/**
 * 16:9, matching the aspect the card reserves. 1280px is three times the width
 * a card ever renders at, and next/image resizes and re-encodes per device, so
 * a larger or lossless source would only bloat the repository: the same frame
 * as a 2x PNG is about 2.6MB against roughly 150KB here.
 */
const WIDTH = 1280;
const HEIGHT = 720;
const QUALITY = 82;
const MANIFEST = path.join(ROOT, "src", "lib", "previews.ts");

/** Rebuild the manifest from the files on disk, so partial runs keep earlier captures. */
async function writeManifest() {
  const files = (await readdir(OUT_DIR)).filter((f) => f.endsWith(".jpg")).sort();
  const rows = files
    .map((f) => `  ${JSON.stringify(f.replace(/\.jpg$/, ""))}: { src: "/previews/${f}", width: ${WIDTH}, height: ${HEIGHT} },`)
    .join("\n");
  const body = `/**
 * GENERATED by \`npm run previews\` — do not edit by hand.
 *
 * The screenshots of deployed projects that actually exist in public/previews.
 * Cards consult this before requesting anything, so a project that has not
 * been captured yet costs no request and logs no 404.
 */
export type Preview = { src: string; width: number; height: number };

export const PREVIEWS: Record<string, Preview> = {${rows ? "\n" + rows + "\n" : ""}};
`;
  await writeFile(MANIFEST, body);
  return files.length;
}

/**
 * Pull { id, name, live } out of src/lib/data/projects.ts without importing TypeScript.
 * The project entries are plain object literals, so a scan is enough and keeps
 * this script dependency-free.
 */
async function readProjects() {
  const src = await readFile(path.join(ROOT, "src", "lib", "data", "projects.ts"), "utf8");
  const body = src.slice(
    src.indexOf("export const projects"),
    src.indexOf("export const projectCategories"),
  );
  const out = [];
  const idRe = /id:\s*"([^"]+)"/g;
  let m;
  while ((m = idRe.exec(body))) {
    const entry = body.slice(m.index, body.indexOf("\n  },", m.index));
    const live = entry.match(/live:\s*"([^"]*)"/);
    const name = entry.match(/name:\s*"([^"]+)"/);
    if (live?.[1]) out.push({ id: m[1], name: name?.[1] ?? m[1], live: live[1] });
  }
  return out;
}

async function main() {
  const filters = process.argv.slice(2).filter((a) => !a.startsWith("-"));
  const all = await readProjects();
  const targets = filters.length
    ? all.filter((p) => filters.some((f) => p.id.includes(f)))
    : all;

  if (!targets.length) {
    console.error("No matching projects with a live URL.");
    process.exitCode = 1;
    return;
  }

  await mkdir(OUT_DIR, { recursive: true });
  // Playwright resolves its own download by default; the override is for
  // sandboxes and CI images that ship Chromium somewhere else.
  const executablePath = process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined;
  const browser = await chromium.launch(executablePath ? { executablePath } : {});
  let failed = 0;

  for (const project of targets) {
    const page = await browser.newPage({
      viewport: { width: WIDTH, height: HEIGHT },
      deviceScaleFactor: 1,
      colorScheme: "dark",
    });
    try {
      await page.goto(project.live, { waitUntil: "networkidle", timeout: 45_000 });
      // Let entrance animations and web fonts settle before the shutter.
      await page.waitForTimeout(2500);
      const buffer = await page.screenshot({ type: "jpeg", quality: QUALITY });
      await writeFile(path.join(OUT_DIR, `${project.id}.jpg`), buffer);
      console.log(
        `  captured  ${project.id.padEnd(16)} ${String(Math.round(buffer.length / 1024)).padStart(4)} KB  ${project.live}`,
      );
    } catch (error) {
      failed += 1;
      console.error(`  FAILED    ${project.id.padEnd(16)} ${error.message.split("\n")[0]}`);
    } finally {
      await page.close();
    }
  }

  await browser.close();
  const listed = await writeManifest();
  console.log(
    `\n${targets.length - failed}/${targets.length} captured · ${listed} listed in src/lib/previews.ts`,
  );
  if (failed) process.exitCode = 1;
}

main();
